// Browser security headers sent with every page. Kept in one small file so they are easy to read and to adjust.
//
// The content-security-policy tells the browser which places the site may load things from. It allows:
//  - the school's own pages, scripts and styles
//  - pictures from any secure address (Admins paste or upload pictures from Cloudinary)
//  - Cloudinary (picture uploads) and Cloudflare Turnstile (the optional "not a robot" check)
// If a future feature ever shows a blank page or a blocked item, this is the place to look.

const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self' https://api.cloudinary.com https://challenges.cloudflare.com",
  "frame-src https://challenges.cloudflare.com",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

export const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
];
